/**
 * The rhythm library, in shorthand.
 *
 * One line per rhythm: its style, name, usual tempo, and a row per drum. In a row "." is silence,
 * "o" a soft hit, "x" a normal one and "X" a loud one; "|" (between bars) and spaces are ignored.
 * Rows: K kick · S snare · C clap · H hat · O open hat · T tom · R rim · Sh shaker · B perc.
 *
 * Unless told otherwise a bar is 16 steps, four to the beat. `steps` and `div` change that
 * (12 × 3 is a bar of 12/8, 12 × 4 a waltz, 20 × 4 a bar of 5/4) and `bars` makes a rhythm
 * longer than one bar: for a fill, or a second bar that answers the first.
 *
 * These are the standard patterns of each style, the ones drum teachers and drum machines use.
 * None is named after a player or a song.
 */
